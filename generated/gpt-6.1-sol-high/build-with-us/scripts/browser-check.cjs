const { chromium } = require('/app/node_modules/playwright-core');
const fs = require('fs');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'], headless: true });
  const results = { consoleErrors: [], pageErrors: [], failedRequests: [], responses: [], viewports: {} };
  for (const [name, viewport] of Object.entries({ desktop: { width: 1440, height: 1000 }, mobile: { width: 390, height: 844 } })) {
    const context = await browser.newContext({ viewport, deviceScaleFactor: 1 });
    const page = await context.newPage();
    page.on('pageerror', e => results.pageErrors.push(e.message));
    page.on('console', msg => { if (msg.type() === 'error') results.consoleErrors.push(msg.text()); });
    page.on('requestfailed', request => results.failedRequests.push({ url: request.url(), error: request.failure().errorText }));
    page.on('response', response => { if (/cloudfront|googleapis|gstatic/.test(response.url())) results.responses.push({ url: response.url(), status: response.status() }); });
    await page.goto('http://127.0.0.1:5173/motionsites-results/build-with-us/', { waitUntil: 'networkidle', timeout: 60000 });
    await page.evaluate(() => document.fonts.ready);
    await page.waitForFunction(() => document.querySelector('video').readyState >= 2, { timeout: 30000 });
    await page.waitForTimeout(1800);
    const layout = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, height: innerHeight, scrollHeight: document.documentElement.scrollHeight, video: { readyState: document.querySelector('video').readyState, paused: document.querySelector('video').paused, width: document.querySelector('video').videoWidth, time: document.querySelector('video').currentTime }, fonts: { inter: document.fonts.check('500 16px Inter'), instrument: document.fonts.check('italic 48px "Instrument Serif"') } }));
    assert.equal(layout.width, layout.scrollWidth, `${name}: horizontal overflow`);
    assert.ok(layout.fonts.inter && layout.fonts.instrument, 'Required fonts must load');
    assert.ok(layout.video.width > 0 && !layout.video.paused, 'Video must play');
    if (name === 'desktop') assert.equal(layout.height, layout.scrollHeight, 'Desktop must fit viewport');
    await page.screenshot({ path: `screenshots/${name}.png`, fullPage: true });
    await page.getByRole('link', { name: 'Start a project' }).click();
    await page.getByRole('button', { name: 'Send my message' }).click();
    assert.equal(await page.getByRole('textbox', { name: 'Full name', exact: true }).evaluate(input => input.validity.valueMissing), true);
    await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Alex Morgan');
    await page.getByRole('textbox', { name: 'Email', exact: true }).fill('alex@example.com');
    await page.getByRole('textbox', { name: 'Project vision' }).fill('A new website and product identity for our studio.');
    const website = page.getByRole('button', { name: 'Website', exact: true });
    await website.click();
    await page.getByRole('button', { name: 'Visual Identity', exact: true }).click();
    assert.equal(await website.getAttribute('aria-pressed'), 'true');
    assert.equal(await page.getByRole('button', { name: 'Visual Identity', exact: true }).getAttribute('aria-pressed'), 'true');
    await website.click();
    assert.equal(await website.getAttribute('aria-pressed'), 'false');
    await page.getByRole('button', { name: 'Send my message' }).click();
    const sending = page.getByRole('button', { name: 'Sending...' });
    await sending.waitFor();
    assert.ok(await sending.isDisabled());
    await page.getByRole('heading', { name: "You're all set!" }).waitFor();
    assert.equal((await page.getByRole('status').innerText()).replace(/\n+/g, '\n'), "✓\nYou're all set!\nExpect a reply within 24 hours.");
    await page.screenshot({ path: `screenshots/${name}-success.png`, fullPage: true });
    results.viewports[name] = { ...layout, checks: ['initial render', 'no horizontal overflow', 'background video autoplay', 'Google Fonts loaded', 'CTA contact anchor', 'required-field validation', 'input entry', 'service multi-select and deselect', 'disabled sending state', 'success replacement'] };
    await context.close();
  }
  await browser.close();
  fs.writeFileSync('screenshots/browser-checks.json', JSON.stringify(results, null, 2));
  console.log(JSON.stringify(results, null, 2));
  assert.equal(results.pageErrors.length, 0);
  assert.equal(results.consoleErrors.length, 0);
})().catch(e => { console.error(e); process.exit(1); });
