const { chromium } = require('/app/node_modules/playwright-core');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = '/motionsites-results/community-superdesign-pill-nav/';
const checks = [];
const server = http.createServer((req, res) => {
  const pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
  const target = path.join('/work/dist', pathname.startsWith(base) ? pathname.slice(base.length) || 'index.html' : 'index.html');
  if (!target.startsWith('/work/dist/') || !fs.existsSync(target)) { res.writeHead(404); res.end(); return; }
  const types = { '.html':'text/html', '.js':'text/javascript', '.css':'text/css', '.svg':'image/svg+xml' };
  res.setHeader('Content-Type', types[path.extname(target)] || 'application/octet-stream');
  res.end(fs.readFileSync(target));
});
(async () => {
  await new Promise(r => server.listen(4173, '0.0.0.0', r));
  const browser = await chromium.launch({ executablePath:'/usr/bin/chromium', headless:true, args:['--no-sandbox','--disable-dev-shm-usage'] });
  const errors = [], failed = [];
  const page = await browser.newPage({ viewport:{width:1440,height:1000}, deviceScaleFactor:1 });
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if(m.type() === 'error') errors.push(m.text()); });
  page.on('requestfailed', r => failed.push(r.url()));
  page.on('response', r => { if(r.status() >= 400) failed.push(`${r.status()} ${r.url()}`); });
  const url = `http://localhost:4173${base}`;
  await page.goto(url); await page.waitForTimeout(1400);
  await assert.equal(await page.title(), 'Pill Navigation');
  const overflow = () => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
  assert(await overflow());
  await page.screenshot({path:'/work/screenshots/desktop.png',fullPage:true});
  checks.push('Desktop 1440x1000: correct title, four navigation links, no horizontal overflow, screenshot saved');
  const collection = page.getByRole('menuitem', {name:'Collection'});
  assert.equal(await page.getByRole('menuitem').count(),4);
  await collection.hover(); await page.waitForTimeout(500);
  const hover = await collection.locator('.hover-circle').evaluate(e => getComputedStyle(e).transform);
  assert(!hover.startsWith('matrix(0,'));
  assert.equal(await collection.locator('.pill-label-hover').evaluate(e => getComputedStyle(e).opacity),'1');
  await page.screenshot({path:'/work/screenshots/desktop-hover.png'});
  await page.mouse.move(0,0); await page.waitForTimeout(400);
  assert.equal(await collection.locator('.pill-label-hover').evaluate(e => getComputedStyle(e).opacity),'0');
  await collection.focus(); await page.waitForTimeout(500);
  assert.equal(await collection.locator('.pill-label-hover').evaluate(e => getComputedStyle(e).opacity),'1');
  await collection.click(); assert.equal(new URL(page.url()).hash,'#/collection');
  assert.equal(await collection.getAttribute('aria-current'),'page');
  checks.push('Desktop: rising circle and label animation, hover reversal, keyboard focus and Collection hash navigation passed');
  await page.getByRole('link',{name:'Home',exact:true}).first().hover();
  await page.waitForTimeout(150);
  const rotation = await page.locator('nav > div').first().locator('a > div').evaluate(e => getComputedStyle(e).transform);
  assert.notEqual(rotation,'none');
  await page.waitForTimeout(900);
  checks.push('Logo hover rotation passed');
  await page.setViewportSize({width:390,height:844});
  await page.goto(url); await page.waitForTimeout(1300);
  assert(await overflow());
  await page.screenshot({path:'/work/screenshots/mobile.png',fullPage:true});
  const toggle = page.getByRole('button',{name:'Toggle menu'});
  await toggle.click(); await page.waitForTimeout(500);
  assert.equal(await toggle.getAttribute('aria-expanded'),'true');
  assert(await page.locator('#mobile-menu').isVisible());
  await page.screenshot({path:'/work/screenshots/mobile-menu.png',fullPage:true});
  await page.locator('#mobile-menu').getByRole('link',{name:'About',exact:true}).click();
  await page.waitForTimeout(500);
  assert.equal(new URL(page.url()).hash,'#/about');
  assert.equal(await toggle.getAttribute('aria-expanded'),'false');
  assert.equal(await page.locator('#mobile-menu').isVisible(),false);
  await toggle.click(); await page.waitForTimeout(500);
  await page.keyboard.press('Escape'); await page.waitForTimeout(400);
  assert.equal(await page.locator('#mobile-menu').isVisible(),false);
  await toggle.click(); await page.waitForTimeout(500); await toggle.click(); await page.waitForTimeout(400);
  assert.equal(await page.locator('#mobile-menu').isVisible(),false);
  assert(await overflow());
  checks.push('Mobile 390x844: no overflow; menu opens/closes, About navigation closes dropdown, Escape dismisses and restores focus; screenshots saved');
  await Promise.all([page.waitForEvent('load'),page.getByRole('button',{name:'Replay Animation'}).click()]);
  await page.waitForTimeout(1200);
  assert(await toggle.isVisible());
  checks.push('Replay Animation reload and entrance completed');
  assert.deepEqual(errors,[]); assert.deepEqual(failed,[]);
  checks.push('No browser script/console errors, failed requests, or HTTP resource errors');
  fs.writeFileSync('/work/screenshots/checks.json', JSON.stringify({passed:true,checks,errors,failed},null,2)+'\n');
  console.log(JSON.stringify({passed:true,checks,errors,failed},null,2));
  await browser.close(); server.close();
})().catch(e => { console.error(e); server.close(); process.exit(1); });
