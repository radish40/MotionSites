const { chromium } = require('/app/node_modules/playwright-core');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = '/motionsites-results/creative-agency/';
const mime = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.mp4': 'video/mp4' };
const server = http.createServer((req, res) => {
  const relative = decodeURIComponent(req.url.split('?')[0]).replace(base, '');
  const file = path.join('/work/dist', relative || 'index.html');
  if (!file.startsWith('/work/dist/') || !fs.existsSync(file)) { res.writeHead(404); res.end(); return; }
  res.writeHead(200, { 'Content-Type': mime[path.extname(file)] || 'application/octet-stream' });
  fs.createReadStream(file).pipe(res);
});
(async () => {
  await new Promise(resolve => server.listen(4173, '0.0.0.0', resolve));
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const report = { url: `http://localhost:4173${base}`, checks: [], consoleErrors: [], pageErrors: [], failedRequests: [], externalResponses: [], viewports: {} };
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
    page.on('pageerror', error => report.pageErrors.push(error.message));
    page.on('console', msg => { if (msg.type() === 'error') report.consoleErrors.push(msg.text()); });
    page.on('requestfailed', req => report.failedRequests.push({ url: req.url(), failure: req.failure()?.errorText }));
    page.on('response', res => { if (!res.url().includes('localhost')) report.externalResponses.push({ url: res.url(), status: res.status() }); });
    await page.goto(report.url, { waitUntil: 'load' });
    await page.evaluate(() => document.fonts.ready);
    await page.waitForFunction(() => document.querySelector('video').readyState >= 2, null, { timeout: 20000 }).catch(() => {});
    assert.equal(await page.title(), 'Creative Agency');
    assert.equal(await page.locator('h1').innerText(), 'creative\nstudio');
    assert.equal(await page.getByRole('button').count(), 7);
    report.checks.push('Title, headline, and seven specified buttons present');
    const read = () => page.evaluate(() => ({ width: innerWidth, height: innerHeight, documentWidth: document.documentElement.scrollWidth, documentHeight: document.documentElement.scrollHeight, fonts: [...document.fonts].map(f => ({ family: f.family, status: f.status })), video: { src: document.querySelector('video').src, readyState: document.querySelector('video').readyState, currentTime: document.querySelector('video').currentTime, paused: document.querySelector('video').paused, muted: document.querySelector('video').muted, loop: document.querySelector('video').loop, playsInline: document.querySelector('video').playsInline, error: document.querySelector('video').error?.message || null } }));
    report.viewports.desktop = await read();
    assert.equal(report.viewports.desktop.video.error, null);
    assert.equal(report.viewports.desktop.video.paused, false);
    assert.equal(report.viewports.desktop.video.muted, true);
    assert.equal(report.viewports.desktop.video.loop, true);
    assert.equal(report.viewports.desktop.video.playsInline, true);
    assert.ok(report.viewports.desktop.video.readyState >= 2);
    assert.ok(report.viewports.desktop.fonts.some(f => f.family === 'Inter' && f.status === 'loaded'));
    assert.ok(report.viewports.desktop.fonts.some(f => f.family === 'Britanica-Black' && f.status === 'loaded'));
    report.checks.push('Exact remote video plays muted with loop and playsInline; Inter and Britanica-Black loaded');
    assert.equal(report.viewports.desktop.documentWidth, 1440);
    assert.equal(report.viewports.desktop.documentHeight, 1000);
    await page.screenshot({ path: '/work/screenshots/desktop.png', fullPage: true });
    const reservation = page.getByRole('button', { name: 'Reservations', exact: true });
    await reservation.hover(); await page.waitForTimeout(200);
    assert.equal(await reservation.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 255, 255)');
    assert.equal(await reservation.evaluate(el => getComputedStyle(el).color), 'rgb(220, 38, 38)');
    const rituals = page.getByRole('button', { name: 'RITUALS', exact: true });
    await rituals.hover(); await page.waitForTimeout(200);
    assert.equal(await rituals.evaluate(el => getComputedStyle(el).borderTopColor), 'rgb(255, 255, 255)');
    const instagram = page.getByRole('button', { name: 'Instagram', exact: true });
    await instagram.hover(); await page.waitForTimeout(200);
    assert.equal(await instagram.evaluate(el => getComputedStyle(el).opacity), '0.7');
    const begin = page.getByRole('button', { name: 'begin now', exact: true });
    await begin.hover(); await page.waitForTimeout(200);
    assert.equal(await begin.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(243, 244, 246)');
    await page.mouse.down(); await page.waitForTimeout(200);
    assert.match(await begin.evaluate(el => getComputedStyle(el).transform), /0\.95/);
    await page.mouse.up();
    report.checks.push('Reservations colors, nav border, Instagram opacity, begin now hover and active scale verified');
    assert.equal(await page.locator('[style*="backdrop-filter"]').first().evaluate(el => getComputedStyle(el).backdropFilter), 'blur(10px)');
    report.checks.push('Stat cards use blur(10px)');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.mouse.move(389, 0); await page.waitForTimeout(250);
    report.viewports.mobile = await read();
    assert.equal(report.viewports.mobile.documentWidth, 390);
    assert.equal(await rituals.isVisible(), false);
    assert.equal(await page.getByRole('button', { name: 'Send', exact: true }).isVisible(), false);
    assert.equal(await instagram.isVisible(), true);
    await page.screenshot({ path: '/work/screenshots/mobile.png', fullPage: true });
    report.checks.push('1440x1000 desktop and 390x844 mobile: no horizontal overflow; mobile navigation visibility correct; full-page screenshots saved');
    assert.deepEqual(report.pageErrors, []);
    assert.deepEqual(report.consoleErrors, []);
    report.checks.push('No JavaScript page errors');
  } finally {
    fs.writeFileSync('/work/screenshots/browser-report.json', JSON.stringify(report, null, 2));
    await browser.close(); server.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; server.close(); });
