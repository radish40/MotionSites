const { chromium } = require('/app/node_modules/playwright-core');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  const errors = [], warnings = [], failedRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); if (msg.type() === 'warning') warnings.push(msg.text()); });
  page.on('requestfailed', req => { if (req.failure()?.errorText !== 'net::ERR_ABORTED') failedRequests.push({url: req.url(), error: req.failure()?.errorText}); });
  await page.goto('http://localhost:4173/motionsites-results/creative-portfolio/', { waitUntil: 'networkidle', timeout: 120000 });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(2000);
  const fontLoaded = await page.evaluate(() => document.fonts.check('500 16px Figtree'));
  const videoState = () => page.locator('video').evaluateAll(videos => videos.map(v => ({ src: v.currentSrc, readyState: v.readyState, paused: v.paused, width: v.videoWidth, height: v.videoHeight, error: v.error?.message || null })));
  const desktopVideos = await videoState();
  assert(desktopVideos.every(v => v.readyState >= 2 && v.width > 0 && !v.paused && v.src.startsWith('blob:')), 'All videos should preload as blobs and play');
  assert(fontLoaded, 'Figtree should load');
  const overflow = () => page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(await overflow(), false);
  await page.screenshot({ path: 'screenshots/desktop.png', fullPage: true });
  const before = await page.locator('.clock').innerText();
  await page.waitForTimeout(1100);
  assert.notEqual(await page.locator('.clock').innerText(), before);
  for (let index = 0; index < 3; index++) {
    await page.locator('.switcher button').nth(index).click();
    await page.waitForTimeout(1300);
    assert.equal(await page.locator('.switcher button').nth(index).getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('video').nth(index).evaluate(v => getComputedStyle(v).opacity), '1');
    assert.equal(await page.locator('.accent').evaluate(e => getComputedStyle(e).color), index === 0 ? 'rgb(245, 152, 242)' : 'rgb(255, 255, 255)');
  }
  await page.locator('.project-button').hover();
  await page.waitForTimeout(550);
  assert.equal(await page.locator('.project-button').evaluate(e => getComputedStyle(e).color), 'rgb(0, 0, 0)');
  assert.equal(await page.locator('.project-button').getAttribute('href'), 'mailto:Davies@gmail.com');
  await page.setViewportSize({ width: 1024, height: 768 });
  assert.equal(await overflow(), false);
  assert.equal(await page.locator('.name').evaluate(e => getComputedStyle(e).fontSize), '129.6px');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.switcher button').first().click();
  await page.mouse.move(380, 100);
  await page.waitForTimeout(1500);
  assert.equal(await overflow(), false);
  await page.screenshot({ path: 'screenshots/mobile.png', fullPage: true });
  const menu = page.getByRole('button', { name: 'Menu', exact: true });
  await menu.click();
  await page.waitForTimeout(500);
  assert.equal(await page.getByRole('button', { name: 'Close', exact: true }).getAttribute('aria-expanded'), 'true');
  assert(await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: '02 / Services' }).isVisible());
  await page.screenshot({ path: 'screenshots/mobile-menu.png', fullPage: true });
  await page.keyboard.press('Escape');
  assert.equal(await menu.getAttribute('aria-expanded'), 'false');
  await menu.click();
  await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: '03 / About' }).click();
  assert.equal(await menu.getAttribute('aria-expanded'), 'false');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.locator('.status-dot').evaluate(e => getComputedStyle(e).animationName), 'none');
  await page.waitForFunction(() => Array.from(document.querySelectorAll('video')).every(video => video.paused));
  assert((await videoState()).every(v => v.paused));
  await page.setViewportSize({ width: 320, height: 740 });
  assert.equal(await overflow(), false);
  assert.deepEqual(errors, []);
  const result = { desktop: '1440x1000', mobile: '390x844', additionalWidths: [1024, 320], fontLoaded, desktopVideos, checks: ['video blob preloading and playback', 'all three crossfades and accent changes', 'live clock updates', 'CTA hover and email destination', 'mobile menu open / Escape / navigation close', 'reduced motion pauses videos and disables animation', 'no horizontal overflow', 'no JavaScript or console errors'], errors, warnings, failedRequests };
  fs.writeFileSync('screenshots/browser-report.json', JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
