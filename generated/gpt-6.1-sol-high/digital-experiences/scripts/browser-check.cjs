const { chromium } = require('/app/node_modules/playwright-core');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const server = spawn('node', ['node_modules/vite/bin/vite.js', 'preview', '--host', '0.0.0.0', '--port', '4173'], { stdio: 'pipe' });
const base = 'http://localhost:4173/motionsites-results/digital-experiences/';
const report = { url: base, checks: [], errors: [], failedRequests: [], canceledRequests: [], assets: [], viewports: {} };
const check = (name, value) => { report.checks.push({ name, passed: !!value }); assert(value, name); };
(async () => {
  let browser;
  try {
    for(let i=0;i<40;i++){try {if((await fetch(base)).ok) break;}catch{} await new Promise(r=>setTimeout(r,250));}
    browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage', '--autoplay-policy=no-user-gesture-required'] });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read','clipboard-write'] });
    const page = await context.newPage();
    page.on('pageerror', e => report.errors.push(e.message));
    page.on('console', m => { if(m.type()==='error') report.errors.push(m.text()); });
    page.on('requestfailed', r => { const item={url:r.url(),error:r.failure()?.errorText}; (item.error==='net::ERR_ABORTED' ? report.canceledRequests : report.failedRequests).push(item); });
    page.on('response', r => { if (/fonts\.|\.mp4/.test(r.url())) report.assets.push({url:r.url(),status:r.status()}); });
    await page.goto(base, {waitUntil:'networkidle'});
    await page.evaluate(()=>document.fonts.ready);
    await page.waitForTimeout(2500);
    check('Exactly two main sections', await page.locator('main > section').count()===2);
    check('Instrument Serif and Barlow loaded', await page.evaluate(()=>document.fonts.check('italic 24px "Instrument Serif"') && document.fonts.check('300 16px Barlow')));
    check('Both background videos decoded', await page.locator('main video').evaluateAll(vs=>vs.every(v=>v.readyState>=2 && v.videoWidth>0)));
    check('Background videos autoplay muted inline', await page.locator('main video').evaluateAll(vs=>vs.every(v=>v.muted&&v.playsInline&&!v.paused)));
    check('Desktop hero fills viewport', await page.locator('#home').evaluate(el=>el.getBoundingClientRect().height===1000));
    await page.locator('main video').evaluateAll(vs=>vs.forEach(v=>{v.pause();v.currentTime=3;}));
    await page.waitForTimeout(600);
    const measure = () => page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,height:innerHeight,sections:[...document.querySelectorAll('main > section')].map(e=>({id:e.id,height:e.getBoundingClientRect().height})), fonts:[...document.fonts].map(f=>({family:f.family,status:f.status}))}));
    report.viewports.desktop=await measure();
    check('No desktop horizontal overflow', report.viewports.desktop.scrollWidth===1440);
    await page.screenshot({path:'screenshots/desktop.png'});
    await page.getByRole('link',{name:'Services',exact:true}).click();
    await page.waitForTimeout(1700);
    check('Services navigation reaches capabilities', await page.locator('#capabilities').evaluate(el=>Math.abs(el.getBoundingClientRect().top)<2));
    await page.screenshot({path:'screenshots/desktop-capabilities.png'});
    await page.getByRole('button',{name:'Contact',exact:true}).click();
    check('Contact opens project dialog', await page.locator('dialog').evaluate(el=>el.open));
    await page.getByLabel('Your name').fill('Browser Check');
    await page.getByLabel('Email address').fill('check@example.com');
    await page.getByLabel('A little about your project').fill('A brand-defining digital experience.');
    await page.getByRole('button',{name:'Copy project brief',exact:true}).click();
    await page.getByRole('button',{name:'Project brief copied'}).waitFor();
    check('Project brief copies to clipboard', (await page.evaluate(()=>navigator.clipboard.readText())).includes('A brand-defining digital experience.'));
    await page.keyboard.press('Escape');
    check('Escape closes dialog', await page.locator('dialog').evaluate(el=>!el.open));
    await page.getByRole('link',{name:'Digital Experiences home'}).click();
    await page.waitForTimeout(1200);
    await page.getByRole('button',{name:'Watch Showreel'}).click();
    check('Showreel opens native video player', await page.locator('dialog video').evaluate(v=>v.controls));
    await page.getByRole('button',{name:'Close dialog'}).click();
    check('Close button closes showreel', await page.locator('dialog').evaluate(el=>!el.open));
    await page.setViewportSize({width:390,height:844});
    await page.goto(base,{waitUntil:'networkidle'});
    await page.waitForTimeout(2500);
    await page.locator('main video').evaluateAll(vs=>vs.forEach(v=>{v.pause();v.currentTime=3;}));
    await page.waitForTimeout(600);
    report.viewports.mobile=await measure();
    check('No mobile horizontal overflow', report.viewports.mobile.scrollWidth===390);
    check('Desktop navigation hidden on mobile', !await page.getByRole('link',{name:'Services',exact:true}).isVisible());
    check('Mobile trust bar fits within hero', await page.locator('.trust-bar').evaluate(el=>el.getBoundingClientRect().bottom<=844));
    await page.screenshot({path:'screenshots/mobile.png'});
    await page.getByRole('button',{name:'Start a Project',exact:true}).click();
    check('Mobile project CTA works', await page.locator('dialog').evaluate(el=>el.open));
    await page.keyboard.press('Escape');
    await page.locator('#capabilities').evaluate(el=>window.scrollTo({top:el.offsetTop,behavior:'instant'}));
    await page.evaluate(()=>document.activeElement?.blur());
    await page.waitForTimeout(1500);
    check('Mobile capabilities grid is single column', await page.locator('.capability-card').evaluateAll(cs=>cs.every(c=>c.getBoundingClientRect().x===cs[0].getBoundingClientRect().x)));
    await page.screenshot({path:'screenshots/mobile-capabilities.png'});
    // Exercise actual loop behavior by moving the first video to its end.
    await page.getByRole('link',{name:'Digital Experiences home'}).click();
    await page.waitForTimeout(1200);
    await page.locator('main video').first().evaluate(v=>{v.currentTime=v.duration-.2;void v.play();});
    await page.waitForFunction(()=>{const v=document.querySelector('main video');return v.currentTime<3&&!v.paused&&getComputedStyle(v).opacity==='1';},{},{timeout:10000});
    report.loopState = await page.locator('main video').first().evaluate(v=>({currentTime:v.currentTime,duration:v.duration,paused:v.paused,opacity:getComputedStyle(v).opacity}));
    check('Fading video restarts after ending', await page.locator('main video').first().evaluate(v=>v.currentTime<3&&!v.paused&&getComputedStyle(v).opacity==='1'));
    check('No browser script or console errors',report.errors.length===0);
    check('No failed external asset requests',report.failedRequests.length===0);
    report.status='passed';
  } catch(e) { report.status='failed';report.failure=e.stack;process.exitCode=1; }
  finally { fs.writeFileSync('screenshots/browser-checks.json',JSON.stringify(report,null,2)); console.log(JSON.stringify(report,null,2));if(browser) await browser.close();server.kill(); }
})();
