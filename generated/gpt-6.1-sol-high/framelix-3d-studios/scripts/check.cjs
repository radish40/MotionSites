const { chromium } = require('/app/node_modules/playwright-core');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ executablePath:'/usr/bin/chromium', headless:true, args:['--no-sandbox','--disable-dev-shm-usage','--autoplay-policy=no-user-gesture-required'] });
  const results = [];
  for (const [name, viewport] of [['desktop', {width:1440,height:1000}], ['mobile', {width:390,height:844}]]) {
    const page = await browser.newPage({ viewport, deviceScaleFactor:1 });
    const errors = [], failedRequests = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('requestfailed', r => failedRequests.push({ url:r.url(), error:r.failure()?.errorText }));
    await page.goto('http://127.0.0.1:5173/motionsites-results/framelix-3d-studios/', {waitUntil:'networkidle'});
    await page.evaluate(() => document.fonts.ready);
    await page.waitForFunction(() => [...document.querySelectorAll('main video')].every(v => v.readyState >= 3));
    await page.waitForTimeout(1600);
    const videos = await page.locator('main video').evaluateAll(videos => videos.map(v => ({width:v.videoWidth,height:v.videoHeight,duration:v.duration,paused:v.paused,currentTime:v.currentTime,error:v.error?.message ?? null})));
    assert(videos.every(v => !v.paused && v.currentTime > 0 && !v.error));
    const overflow = await page.evaluate(() => ({scroll:document.documentElement.scrollWidth, viewport:innerWidth}));
    assert(overflow.scroll <= overflow.viewport, 'Horizontal overflow');
    await page.screenshot({path:`screenshots/${name}.png`, fullPage:true});
    await page.getByRole('button', {name:'Explore Reel'}).click();
    await page.waitForFunction(() => document.querySelector('.reel-dialog').open);
    await page.locator('.reel-dialog video').evaluate(v => v.muted = true);
    await page.getByRole('button', {name:'Close reel'}).click();
    assert.equal(await page.locator('.reel-dialog').evaluate(d => d.open), false);
    await page.getByRole('button', {name:'Buy Now', exact:true}).click();
    assert.equal(await page.locator('.cart-dialog').evaluate(d => d.open), true);
    assert.equal(await page.getByRole('button', {name:'Open cart, 1 items'}).count(), 1);
    await page.getByRole('button', {name:'Remove',exact:true}).click();
    await page.getByText('Your cart is empty.').waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.cart-dialog').evaluate(d => d.open), false);
    await page.getByRole('button', {name:'Open cart, 0 items'}).click();
    await page.getByRole('button', {name:'Explore 3D OS'}).click();
    await page.waitForTimeout(500);
    assert.equal(await page.locator('.cart-dialog').evaluate(d => d.open), false);
    const navHidden = await page.locator('.desktop-nav').isHidden();
    assert.equal(navHidden, name === 'mobile');
    const fontLoaded = await page.evaluate(() => document.fonts.check('500 26px Inter'));
    assert(fontLoaded, 'Inter font did not load');
    const marquee = await page.locator('.marquee-track').evaluate(e => getComputedStyle(e).animationName);
    assert.equal(marquee, 'marquee');
    assert.equal(errors.length, 0, errors.join('\n'));
    results.push({ viewport:name, dimensions:viewport, videos, overflow, navHidden, marquee, fontLoaded, scriptErrors:errors, failedRequests, interactions:['reel opens and closes','Buy Now adds product and opens cart','Remove empties cart','Escape closes cart','empty cart CTA navigates to shipping'] });
    await page.close();
  }
  const reducedPage = await browser.newPage({ viewport:{width:768,height:1024}, reducedMotion:'reduce' });
  await reducedPage.goto('http://127.0.0.1:5173/motionsites-results/framelix-3d-studios/', {waitUntil:'networkidle'});
  assert.equal(await reducedPage.locator('.marquee-track').evaluate(e => getComputedStyle(e).animationName), 'none');
  assert(await reducedPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await reducedPage.close();
  fs.writeFileSync('screenshots/browser-checks.json', JSON.stringify(results,null,2));
  console.log(JSON.stringify(results,null,2));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
