const { chromium } = require('/app/node_modules/playwright-core');
const http = require('http');
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const base = '/motionsites-results/growth-marketing-saas/';
const server = http.createServer((req,res) => {
 const file = path.join('/work/dist', decodeURIComponent(req.url.split('?')[0]).replace(base,'') || 'index.html');
 const target = fs.existsSync(file) && fs.statSync(file).isFile() ? file : '/work/dist/index.html';
 res.setHeader('Content-Type', ({'.html':'text/html','.js':'application/javascript','.css':'text/css','.png':'image/png'})[path.extname(target)] || 'application/octet-stream');
 res.end(fs.readFileSync(target));
});
(async () => {
 await new Promise(r => server.listen(4173, '0.0.0.0', r));
 const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const report = { desktop: {}, mobile: {}, errors: [], failedRequests: [], assets: [] };
 const context = await browser.newContext({viewport:{width:1440,height:1000}});
 const page = await context.newPage();
 page.on('pageerror',e => report.errors.push(e.message));
 page.on('requestfailed',r => { if (!r.failure()?.errorText.includes('ERR_ABORTED')) report.failedRequests.push({url:r.url(),error:r.failure()?.errorText}); });
 page.on('response',r => {if(r.status()>=400) report.assets.push({url:r.url(),status:r.status()});});
 await page.goto('http://127.0.0.1:4173'+base,{waitUntil:'networkidle',timeout:90000});
 await page.evaluate(() => document.fonts.ready);
 await page.waitForTimeout(2000);
 const inspect = () => ({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,height:document.documentElement.scrollHeight,fonts: {inter:document.fonts.check('16px Inter'),serif:document.fonts.check('16px "Instrument Serif"'),icons:document.fonts.check('16px "Material Symbols Outlined"')},videos:[...document.querySelectorAll('video')].map(v=>({src:v.src,readyState:v.readyState,error:v.error?.message||null,paused:v.paused,currentTime:v.currentTime,duration:v.duration,opacity:getComputedStyle(v).opacity})),grass:[...document.images].map(i=>({src:i.src,loaded:i.complete&&i.naturalWidth>0}))});
 report.desktop = await page.evaluate(inspect);
 assert.equal(report.desktop.width,report.desktop.scrollWidth,'Desktop overflow');
 await page.screenshot({path:'/work/screenshots/desktop.png'});
 await page.screenshot({path:'/work/screenshots/desktop-full.png',fullPage:true});
 await page.getByRole('button',{name:'Get course',exact:true}).click();
 await page.waitForTimeout(800);
 report.desktop.ctaScroll = await page.evaluate(()=>scrollY>0);
 assert(report.desktop.ctaScroll);
 const input=page.getByRole('textbox',{name:'Ask about the course',exact:true});
 await input.fill('How do I make a video hero?'); await input.press('Enter');
 await page.waitForTimeout(700);
 assert(await page.getByText('How do I make a video hero?',{exact:true}).count());
 report.desktop.chatEnter = await page.getByRole('log').evaluate(el=>({messages:el.children.length,atBottom:el.scrollHeight-el.scrollTop-el.clientHeight<5}));
 await input.fill('Tell me more'); await page.getByRole('button',{name:'Send message',exact:true}).click();
 await page.waitForTimeout(600); assert(await page.getByText('Tell me more',{exact:true}).count()); report.desktop.chatSend = true;
 await input.fill('Line one'); await input.press('Shift+Enter'); await input.type('Line two'); assert((await input.inputValue()).includes('\n')); report.desktop.shiftEnter = true;
 await page.getByRole('textbox',{name:'Email address'}).fill('builder@example.com'); await page.getByRole('button',{name:'Subscribe',exact:true}).click();
 assert(await page.getByText('Thanks for your interest!',{exact:false}).count()); report.desktop.emailPreview = true;
 await page.evaluate(()=>scrollTo(0,0)); await page.waitForTimeout(500);
 const before=await page.locator('[data-parallax]').evaluate(el=>getComputedStyle(el).transform);
 await page.evaluate(()=>scrollTo(0,200)); await page.waitForTimeout(500);
 const after=await page.locator('[data-parallax]').evaluate(el=>getComputedStyle(el).transform);
 assert.notEqual(before,after);report.desktop.parallax={before,after};
 // Exercise the custom video loop at its real duration boundary.
 const preview = page.locator('video').nth(1);
 await preview.evaluate(v=>{if(Number.isFinite(v.duration))v.currentTime=v.duration-.7;});
 await page.waitForFunction(() => { const v=document.querySelectorAll('video')[1]; return v.currentTime > 0 && v.currentTime < 3 && !v.paused && Number(v.style.opacity) > .9; }, null, {timeout:30000});
 report.desktop.videoLoop=await preview.evaluate(v=>({currentTime:v.currentTime,paused:v.paused,opacity:getComputedStyle(v).opacity}));
 await context.close();
 const mobileContext=await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1,hasTouch:true});
 const mobile=await mobileContext.newPage(); mobile.on('pageerror',e=>report.errors.push(e.message));
 await mobile.goto('http://127.0.0.1:4173'+base,{waitUntil:'networkidle',timeout:90000}); await mobile.evaluate(()=>document.fonts.ready);await mobile.waitForTimeout(2000);
 report.mobile=await mobile.evaluate(inspect);assert.equal(report.mobile.width,report.mobile.scrollWidth,'Mobile overflow');
 await mobile.screenshot({path:'/work/screenshots/mobile.png'});
 await mobile.screenshot({path:'/work/screenshots/mobile-full.png',fullPage:true});
 await mobile.getByRole('button',{name:'Open menu'}).click();await mobile.getByRole('dialog').waitFor();
 assert(await mobile.getByRole('dialog').getByRole('link',{name:'What you get',exact:true}).isVisible());
 await mobile.screenshot({path:'/work/screenshots/mobile-menu.png'});
 await mobile.keyboard.press('Escape');await mobile.getByRole('dialog').waitFor({state:'hidden'}); report.mobile.sheetEscape=true;
 await mobile.getByRole('button',{name:'Open menu'}).click();await mobile.getByRole('dialog').getByRole('link',{name:'Features',exact:true}).click();
 await mobile.waitForTimeout(700);assert.equal(await mobile.getByRole('dialog').count(),0);report.mobile.sheetNavigation=await mobile.evaluate(()=>scrollY>0);assert(report.mobile.sheetNavigation);
 await mobileContext.close();
 const reduced=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});const rp=await reduced.newPage();await rp.goto('http://127.0.0.1:4173'+base);await rp.waitForTimeout(1000);await rp.evaluate(()=>scrollTo(0,200));await rp.waitForTimeout(300);report.reducedMotion=await rp.locator('[data-parallax]').evaluate(el=>getComputedStyle(el).transform);await reduced.close();
 assert.equal(report.errors.length,0,'Script errors');
 assert.equal(report.failedRequests.length,0,'Failed asset requests');
 for (const size of ['desktop','mobile']) { assert(Object.values(report[size].fonts).every(Boolean),'Fonts loaded'); assert(report[size].grass.every(x=>x.loaded),'Grass loaded'); assert(report[size].videos.every(x=>x.readyState>=2&&!x.error&&!x.paused),'Videos playing'); }
 fs.writeFileSync('/work/checks/browser-results.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2)); await browser.close(); server.close();
})().catch(e=>{console.error(e);server.close();process.exit(1);});
