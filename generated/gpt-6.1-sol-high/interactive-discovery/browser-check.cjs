const { chromium } = require('/app/node_modules/playwright-core');
const fs = require('fs');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless:true, args:['--no-sandbox','--disable-dev-shm-usage'] });
 const report = { errors: [], failedRequests: [], assets: [], checks: {} };
 const context = await browser.newContext({ viewport: { width:1440,height:1000 }, deviceScaleFactor:1 });
 const page = await context.newPage();
 page.on('pageerror', e => report.errors.push(e.message));
 page.on('requestfailed', r => report.failedRequests.push({url:r.url(),error:r.failure()?.errorText}));
 page.on('response', r => {if (/higgs|googleapis|gstatic/.test(r.url())) report.assets.push({url:r.url(),status:r.status()});});
 await page.goto('http://localhost:4173/motionsites-results/interactive-discovery/',{waitUntil:'domcontentloaded'});
 await page.waitForTimeout(6000);
 report.checks.desktopOverflow = await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
 report.checks.desktopHeading = await page.locator('h1').innerText();
 await page.screenshot({path:'screenshots/desktop.png'});
 await page.mouse.move(720,570);
 await page.waitForTimeout(900);
 report.checks.revealMask = await page.getByTestId('reveal-layer').evaluate(el=>el.style.maskImage.startsWith('url("data:image/png'));
 await page.screenshot({path:'screenshots/spotlight.png'});
 await page.getByRole('button',{name:'Start Digging',exact:true}).click();
 await page.getByRole('status').waitFor();
 report.checks.startDigging = true;
 await page.getByRole('button',{name:'Geology',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Geology',exact:true}).getAttribute('aria-pressed'),'true');
 report.checks.navigation = true;
 await page.getByRole('button',{name:'Sign Up',exact:true}).click();
 await page.locator('#email').fill('explorer@example.com');
 await page.locator('dialog').getByRole('button',{name:'Sign Up',exact:true}).click();
 await page.getByText('Curiosity begins here.').waitFor();
 await page.keyboard.press('Escape');
 report.checks.signupAndEscape = true;
 const mobile = await context.newPage({viewport:{width:390,height:844}});
 // A separate context ensures a real touch-enabled mobile viewport.
 await mobile.close();
 const mobileContext = await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const mp = await mobileContext.newPage();
 mp.on('pageerror',e=>report.errors.push(e.message));
 await mp.goto('http://localhost:4173/motionsites-results/interactive-discovery/',{waitUntil:'domcontentloaded'});
 await mp.waitForTimeout(3000);
 report.checks.mobileOverflow = await mp.evaluate(()=>document.documentElement.scrollWidth<=innerWidth && document.documentElement.scrollHeight<=innerHeight);
 await mp.screenshot({path:'screenshots/mobile.png'});
 await mp.getByRole('button',{name:'Open menu',exact:true}).click();
 await mp.getByRole('button',{name:'Field Guides',exact:true}).click();
 assert.equal(await mp.getByRole('button',{name:'Open menu',exact:true}).getAttribute('aria-expanded'),'false');
 report.checks.mobileMenu = true;
 await mp.getByRole('button',{name:'Start Digging',exact:true}).tap();
 await mp.getByRole('status').waitFor();
 report.checks.mobileDigging = true;
 await mp.evaluate(()=>window.dispatchEvent(new Event('resize')));
 const reduced = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 const rp=await reduced.newPage();
 await rp.goto('http://localhost:4173/motionsites-results/interactive-discovery/',{waitUntil:'domcontentloaded'});
 report.checks.reducedMotion = await rp.locator('h1 span').first().evaluate(el=>getComputedStyle(el).opacity==='1' && getComputedStyle(el).animationName==='none');
 report.checks.imageLoads = await page.evaluate(async()=> {
   const urls = [...document.querySelectorAll('[data-testid$="layer"]')].map(el=>getComputedStyle(el).backgroundImage.slice(5,-2));
   return await Promise.all(urls.map(url=>new Promise(resolve=> { const i=new Image();const t=setTimeout(()=>resolve({url,loaded:false,reason:'timeout'}),15000);i.onload=()=>{clearTimeout(t);resolve({url,loaded:true,width:i.naturalWidth,height:i.naturalHeight})};i.onerror=()=>{clearTimeout(t);resolve({url,loaded:false,reason:'error'})};i.src=url; })));
 });
 report.checks.fonts = await page.evaluate(()=>({inter:document.fonts.check('14px Inter'),playfair:document.fonts.check('italic 96px "Playfair Display"')}));
 fs.writeFileSync('browser-report.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
