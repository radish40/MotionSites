const { chromium } = require('/app/node_modules/playwright-core');
const fs = require('fs');
const http = require('http');
const path = require('path');
const base = '/motionsites-results/luxury-focus/';
const types = {'.html':'text/html','.js':'application/javascript','.css':'text/css'};
const server = http.createServer((req,res)=>{
  let name = decodeURIComponent(req.url.split('?')[0]);
  if(!name.startsWith(base)){res.writeHead(404);res.end();return;}
  name = name.slice(base.length) || 'index.html';
  const file = path.join('/work/dist',name);
  if(!fs.existsSync(file)){res.writeHead(404);res.end();return;}
  res.setHeader('Content-Type',types[path.extname(file)]||'application/octet-stream');fs.createReadStream(file).pipe(res);
});
(async()=>{
 await new Promise(r=>server.listen(4173,'0.0.0.0',r));
 const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const report={errors:[],failedRequests:[],assets:[],checks:[]};
 const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 page.on('pageerror',e=>report.errors.push(e.message));
 page.on('requestfailed',r=>report.failedRequests.push({url:r.url(),error:r.failure()?.errorText}));
 page.on('response',r=>{if(/cloudinary|googleapis|gstatic/.test(r.url())) report.assets.push({url:r.url(),status:r.status()});});
 const check=(name,pass,details)=>{report.checks.push({name,pass,details});if(!pass)console.log('FAIL',name,details);};
 await page.goto('http://localhost:4173'+base,{waitUntil:'networkidle',timeout:90000});
 await page.evaluate(()=>document.fonts.ready);
 await page.waitForTimeout(2500);
 const media=()=>page.evaluate(()=>({videos:[...document.querySelectorAll('video')].map(v=>({readyState:v.readyState,duration:v.duration,time:v.currentTime,error:v.error?.message})),images:[...document.images].map(i=>({src:i.src,complete:i.complete,width:i.naturalWidth})),fonts:document.fonts.check('16px "Instrument Serif"')}));
 report.initialMedia=await media();
 await page.screenshot({path:'/work/screenshots/desktop.png'});
 const overflow=()=>page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
 check('Desktop has no horizontal overflow',(await overflow()).scrollWidth===1440,await overflow());
 check('Hero headline visible',await page.locator('h1').isVisible());
 const scroll=async p=>{await page.evaluate(p=>window.scrollTo(0,(document.documentElement.scrollHeight-innerHeight)*p),p);await page.waitForTimeout(3200);};
 await scroll(.25);report.firstVideoMidpoint=await media();
 check('First video scrubs',report.firstVideoMidpoint.videos[0].time>0);
 await scroll(.44);
 check('Earrings panel opens',await page.locator('aside').getAttribute('aria-hidden')==='false');
 check('Earrings content',await page.locator('aside h2').innerText()==='18K White Gold & Pink Sapphire');
 await page.getByRole('button',{name:'Increase quantity'}).click();
 check('Quantity increases and price updates',await page.getByTestId('quantity').innerText()==='2' && await page.getByTestId('price').innerText()==='$3,700');
 await page.getByRole('button',{name:'Decrease quantity'}).click();
 check('Quantity minimum',await page.getByRole('button',{name:'Decrease quantity'}).isDisabled());
 await page.getByRole('button',{name:/add to atelier bag/i,exact:true}).click();
 check('Bag provides confirmation',(await page.getByRole('status').innerText()).includes('1 piece added'));
 await page.screenshot({path:'/work/screenshots/desktop-earrings.png'});
 await page.getByRole('button',{name:'Back to series'}).click();await page.waitForTimeout(4200);
 check('First back button closes sheet',await page.locator('aside').getAttribute('aria-hidden')==='true');
 await scroll(.72);report.secondVideoMidpoint=await media();
 check('Second video scrubs',report.secondVideoMidpoint.videos[1].time>0);
 await scroll(0);await page.getByRole('button',{name:'Open atelier bag'}).click();await page.waitForTimeout(4500);
 check('Bag jumps to final ring',await page.locator('aside').getAttribute('aria-hidden')==='false' && await page.locator('aside h2').innerText()==='Sterling Silver Sculpture Ring');
 check('Product changes reset quantity',await page.getByTestId('quantity').innerText()==='1' && await page.getByTestId('price').innerText()==='$1,350');
 await page.screenshot({path:'/work/screenshots/desktop-ring.png'});
 await page.getByRole('button',{name:'Back to series'}).click();await page.waitForTimeout(4000);
 check('Second back button closes sheet',await page.locator('aside').getAttribute('aria-hidden')==='true');
 await page.setViewportSize({width:390,height:844});await scroll(0);await page.waitForTimeout(1500);
 await page.screenshot({path:'/work/screenshots/mobile.png'});
 check('Mobile has no horizontal overflow',(await overflow()).scrollWidth===390,await overflow());
 const heroBounds=await page.locator('h1').boundingBox();check('Mobile hero within viewport',heroBounds.y>=0 && heroBounds.y+heroBounds.height<=844,heroBounds);
 await page.getByRole('button',{name:'Open atelier bag'}).click();await page.waitForTimeout(4500);
 check('Mobile panel opens',await page.locator('aside').getAttribute('aria-hidden')==='false');
 const addBounds=await page.locator('.add-button').boundingBox();check('Mobile purchase button within viewport',addBounds.y>=0 && addBounds.y+addBounds.height<=844,addBounds);
 await page.screenshot({path:'/work/screenshots/mobile-ring.png'});
 check('No script errors',report.errors.length===0,report.errors);
 check('All supplied images load',report.initialMedia.images.every(i=>i.complete && i.width>0));
 check('Both videos loaded',report.initialMedia.videos.every(v=>v.readyState>=2 && v.duration>0),report.initialMedia.videos);
 fs.writeFileSync('/work/browser-report.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
 await browser.close();server.close();
 if(report.checks.some(c=>!c.pass))process.exitCode=1;
})().catch(e=>{console.error(e);server.close();process.exit(1);});
