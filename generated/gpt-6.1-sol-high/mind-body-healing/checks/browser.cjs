const { chromium } = require('/app/node_modules/playwright-core');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
(async () => {
 const server = spawn('node', ['node_modules/vite/bin/vite.js', 'preview', '--host', '0.0.0.0', '--port', '4173'], {stdio:'inherit'});
 let browser;
 try {
  await new Promise(r=>setTimeout(r,1800));
  browser = await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage']});
  const errors=[], assetIssues=[], mediaCancellations=[];
  const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('requestfailed',r=>{ const issue={url:r.url(),error:r.failure()?.errorText}; if(r.resourceType()==='media' && issue.error==='net::ERR_ABORTED') mediaCancellations.push(issue); else assetIssues.push(issue); });
  page.on('response',r=>{if(r.status()>=400)assetIssues.push({url:r.url(),status:r.status()});});
  await page.goto('http://127.0.0.1:4173/motionsites-results/mind-body-healing/',{waitUntil:'networkidle',timeout:60000});
  await page.evaluate(()=>document.fonts.ready);
  await page.waitForFunction(()=>{const v=document.querySelector('video');return v.readyState>=3&&!v.paused;},{timeout:30000});
  await page.evaluate(()=>{const v=document.querySelector('video');v.currentTime=3;v.pause();});
  await page.waitForTimeout(500);
  const desktop=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,height:innerHeight,scrollHeight:document.documentElement.scrollHeight,font:document.fonts.check('400 16px Inter'),video:{width:document.querySelector('video').videoWidth,height:document.querySelector('video').videoHeight},images:[...document.images].map(i=>({loaded:i.complete&&i.naturalWidth>0,src:i.src}))}));
  await page.screenshot({path:'screenshots/desktop.png',fullPage:true});
  await page.getByRole('link',{name:'Healing Methods',exact:true}).first().click();
  const desktopNav=await page.evaluate(()=>location.hash==='#healing');
  await page.getByRole('button',{name:'Begin Your Journey'}).hover();
  await page.waitForTimeout(400);
  const ctaHover=await page.getByRole('button',{name:'Begin Your Journey'}).evaluate(e=>getComputedStyle(e).backgroundColor);
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:4173/motionsites-results/mind-body-healing/',{waitUntil:'networkidle'});
  await page.evaluate(()=>document.fonts.ready);
  await page.waitForFunction(()=>document.querySelector('video').readyState>=3);
  await page.evaluate(()=>{const v=document.querySelector('video');v.currentTime=3;v.pause();});
  await page.waitForTimeout(500);
  const mobile=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,height:innerHeight,scrollHeight:document.documentElement.scrollHeight}));
  await page.screenshot({path:'screenshots/mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Open menu'}).click();
  await page.waitForTimeout(600);
  const menuOpens=await page.getByRole('button',{name:'Close menu'}).getAttribute('aria-expanded')==='true';
  const mainHidden=await page.locator('main').evaluate(e=>e.inert&&getComputedStyle(e).opacity==='0');
  await page.screenshot({path:'screenshots/mobile-menu.png',fullPage:true});
  await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('link',{name:'Our Approach'}).click();
  await page.waitForTimeout(600);
  const linkClosesMenu=await page.getByRole('button',{name:'Open menu'}).getAttribute('aria-expanded')==='false';
  await page.getByRole('button',{name:'Open menu'}).click();
  await page.keyboard.press('Escape');
  const escapeClosesMenu=await page.getByRole('button',{name:'Open menu'}).getAttribute('aria-expanded')==='false';
  await page.getByRole('button',{name:'Open menu'}).click();
  await page.setViewportSize({width:1440,height:1000});
  const resizeClosesMenu=await page.locator('main').evaluate(e=>!e.inert);
  const report={desktop,mobile,interactions:{desktopNav,ctaHover,menuOpens,mainHidden,linkClosesMenu,escapeClosesMenu,resizeClosesMenu},errors,assetIssues,mediaCancellations};
  fs.writeFileSync('checks/browser-report.json',JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
  if(errors.length||desktop.scrollWidth>1440||mobile.scrollWidth>390||assetIssues.length||!Object.entries(report.interactions).every(([k,v])=>k==='ctaHover'||v))process.exitCode=1;
 } finally { if(browser)await browser.close();server.kill(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
