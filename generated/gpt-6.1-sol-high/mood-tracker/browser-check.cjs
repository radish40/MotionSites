const {chromium} = require('/app/node_modules/playwright-core');
const fs = require('fs');
const assert = require('assert/strict');
const base='http://127.0.0.1:4173/motionsites-results/mood-tracker/';
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage']});
 const report={errors:[],failedRequests:[],checks:[],viewports:{}};
 for(const [name,viewport] of Object.entries({desktop:{width:1440,height:1000},mobile:{width:390,height:844}})){
  if(process.env.CHECK_VIEWPORT && process.env.CHECK_VIEWPORT!==name)continue;
  const context=await browser.newContext({viewport,deviceScaleFactor:1});
  const page=await context.newPage();
  console.log(`Checking ${name}`);
  page.on('console',m=>{if(m.type()==='error')report.errors.push(`${name}: ${m.text()}`)});
  page.on('pageerror',e=>report.errors.push(`${name}: ${e.message}`));
  page.on('requestfailed',r=>report.failedRequests.push({viewport:name,url:r.url(),error:r.failure()?.errorText}));
  page.on('response',r=>{if(r.status()>=400)report.errors.push(`${name}: HTTP ${r.status()} ${r.url()}`)});
  await page.goto(base,{waitUntil:'networkidle'});
  await page.evaluate(()=>document.fonts.ready);
  await page.waitForTimeout(1500);
  const media=[];
  for(let i=0;i<3;i++){
   const video=page.locator('video').nth(i);
   await video.scrollIntoViewIfNeeded();
   await video.evaluate(async v=>{await v.play()});
   await page.waitForTimeout(200);
   media.push(await video.evaluate(v=>({readyState:v.readyState,playing:!v.paused,width:v.videoWidth,height:v.videoHeight,error:v.error?.message||null})));
  }
  console.log(`${name}: video states`,JSON.stringify(media));
  assert(media.every(v=>v.readyState>=2 && v.playing && !v.error),'Video playback when visible');
  await page.locator('video').evaluateAll(vs=>vs.forEach(v=>{v.pause();v.currentTime=.5;}));
  await page.waitForTimeout(250);
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  const layout=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,phones:[...document.querySelectorAll('.phone')].map(p=>{const r=p.getBoundingClientRect();const c=p.querySelector('.phone-content');return {width:r.width,height:r.height,contentHeight:c.clientHeight,contentScrollHeight:c.scrollHeight}})}));
  console.log(`${name}: layout`,JSON.stringify(layout));
  assert.equal(layout.scrollWidth,viewport.width,'No horizontal page overflow');
  assert(layout.phones.every(p=>p.contentScrollHeight<=p.contentHeight),'No clipped phone content');
  const fontFaces=await page.evaluate(()=>[...document.fonts].map(f=>({family:f.family,status:f.status,weight:f.weight})));
  const fontLoaded=fontFaces.some(f=>f.family.replaceAll('"','')==='Helvetica Neue ME' && f.status==='loaded');
  assert(fontLoaded,'Requested font face is loaded');
  report.viewports[name]={viewport,layout,media,fontLoaded,fontFaces};
  if(name==='mobile')await page.setViewportSize({width:viewport.width,height:await page.evaluate(()=>document.documentElement.scrollHeight)});
  await page.waitForTimeout(700);
  await page.screenshot({path:`/work/screenshots/${name}.png`,fullPage:true});
  if(name==='mobile')await page.setViewportSize(viewport);
  console.log(`${name}: initial screenshot and layout passed`);
  const home=page.locator('#screen-1'); const form=page.locator('#screen-3');
  await home.getByRole('button',{name:'Week',exact:true}).click();
  await home.getByRole('heading',{name:'Your week in view'}).waitFor();
  await home.getByRole('button',{name:'Today',exact:true}).click();
  await home.getByRole('button',{name:'About your check-in'}).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await home.getByRole('button',{name:'Reflect on your day',exact:true}).click();
  await form.getByRole('button',{name:'Settled',exact:true}).click();
  assert.equal(await form.getByRole('button',{name:'Settled',exact:true}).getAttribute('aria-pressed'),'true');
  await form.getByRole('textbox',{name:'Jot your thoughts'}).fill('A walk in the morning light helped me feel grounded.');
  await form.getByRole('button',{name:'Increase energy'}).click();
  assert.equal(await form.getByRole('button',{name:'Increase energy'}).isDisabled(),true);
  for(let i=0;i<4;i++)await form.getByRole('button',{name:'Decrease energy'}).click();
  assert.equal(await form.getByRole('button',{name:'Decrease energy'}).isDisabled(),true);
  await form.getByRole('button',{name:'Set energy to 3',exact:true}).click();
  await form.getByRole('button',{name:'Done',exact:true}).click();
  await form.getByRole('button',{name:'Check-in saved',exact:true}).waitFor();
  console.log(`${name}: check-in saved`);
  const entry=await page.evaluate(()=>JSON.parse(localStorage.getItem('soul-canvas-entries'))[0]);
  assert.equal(entry.mood,'settled');assert.equal(entry.energy,3);assert.match(entry.notes,/morning light/);
  await home.getByRole('button',{name:'Reflection history',exact:true}).click();
  await page.getByRole('dialog').getByText(entry.notes).waitFor();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await home.getByRole('button',{name:'Search reflections',exact:true}).click();
  await page.getByRole('dialog').getByRole('textbox').fill('grounded');
  await page.getByRole('dialog').getByText(entry.notes).waitFor();
  await page.getByRole('dialog').getByRole('textbox').fill('nothing matches');
  await page.getByText('No reflections match your search.').waitFor();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.locator('#screen-2').getByRole('button',{name:'Explore suggestions'}).click();
  await page.getByRole('heading',{name:'Small steps, softer days'}).waitFor();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('soul-canvas-entries')).length),1);
  report.checks.push(`${name}: initial layout, videos, font, period tabs, info, mood, notes, energy limits, save, history, search, suggestions, persisted storage`);
  await context.close();
 }
 await browser.close();
 fs.writeFileSync('/work/screenshots/browser-checks.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
 assert.equal(report.errors.length,0,'No console/page/HTTP errors');
})().catch(e=>{console.error(e);process.exit(1)});
