const { chromium } = require('/app/node_modules/playwright-core');
const fs = require('fs');
const http = require('http');
const path = require('path');
const base = '/motionsites-results/no-code-waitlist/';
const types = {'.html':'text/html','.js':'text/javascript','.css':'text/css','.png':'image/png'};
const server = http.createServer((req,res)=>{
  const relative = decodeURIComponent(req.url.split('?')[0]).replace(base, '');
  const file = path.join('/work/dist', relative || 'index.html');
  if(!file.startsWith('/work/dist/') || !fs.existsSync(file)) {res.writeHead(404); return res.end();}
  res.setHeader('Content-Type',types[path.extname(file)] || 'application/octet-stream'); fs.createReadStream(file).pipe(res);
});
(async()=>{
 await new Promise(r=>server.listen(4173,'0.0.0.0',r));
 const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--autoplay-policy=no-user-gesture-required']});
 const results = {pageErrors:[],failedRequests:[],consoleErrors:[]};
 const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 page.on('pageerror', e=>results.pageErrors.push(e.message));
 page.on('requestfailed',r=>results.failedRequests.push({url:r.url(),error:r.failure()?.errorText}));
 page.on('console',m=>{if(m.type()==='error') results.consoleErrors.push(m.text());});
 await page.goto('http://localhost:4173'+base,{waitUntil:'networkidle'});
 await page.waitForFunction(()=>document.querySelector('video').readyState>=2,{timeout:45000}).catch(e=>results.videoError=e.message);
 await page.evaluate(()=>document.fonts.ready);
 await page.waitForTimeout(1500);
 results.desktop = await page.evaluate(()=>({width:innerWidth,height:innerHeight,scrollWidth:document.documentElement.scrollWidth,scrollHeight:document.documentElement.scrollHeight,video:{readyState:document.querySelector('video').readyState,currentTime:document.querySelector('video').currentTime,videoWidth:document.querySelector('video').videoWidth},fonts:{inter:document.fonts.check('14px Inter'),serif:document.fonts.check('64px "Instrument Serif"')}}));
 await page.screenshot({path:'/work/screenshots/desktop.png'});
 await page.getByRole('button',{name:'Get early access',exact:true}).click();
 const input=page.getByRole('textbox',{name:'Email address'});
 await input.waitFor();
 await page.waitForTimeout(2400);
 results.typewriter = await input.getAttribute('placeholder');
 await input.fill('not-an-email');
 await page.getByRole('button',{name:'Join waitlist'}).click();
 results.invalidEmailRejected = await input.evaluate(e=>!e.validity.valid);
 await input.fill('hello@example.com');
 await page.getByRole('button',{name:'Join waitlist'}).click();
 await page.getByRole('button',{name:'Email submitted'}).waitFor();
 results.submissionConfirmed = await page.getByRole('status').textContent();
 await page.waitForTimeout(4200);
 results.resetsAfterFourSeconds = await page.getByRole('button',{name:'Get early access',exact:true}).isVisible();
 await page.getByRole('button',{name:'Play Video Demo'}).click();
 results.demoOpens = await page.locator('dialog').evaluate(e=>e.open);
 await page.keyboard.press('Escape');
 results.demoCloses = await page.locator('dialog').evaluate(e=>!e.open);
 await page.getByRole('button',{name:'Sign Up',exact:true}).click();
 await input.waitFor();
 results.signUpOpensForm = await input.isVisible();
 await page.reload({waitUntil:'networkidle'});
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(2000);
 results.mobile=await page.evaluate(()=>({width:innerWidth,height:innerHeight,scrollWidth:document.documentElement.scrollWidth,scrollHeight:document.documentElement.scrollHeight,navLinksHidden:getComputedStyle(document.querySelector('nav .hidden')).display==='none'}));
 await page.screenshot({path:'/work/screenshots/mobile.png'});
 await page.getByRole('button',{name:'Get early access',exact:true}).click();
 await input.waitFor();
 results.mobileFormFits=await input.evaluate(e=>{const r=e.closest('form').getBoundingClientRect();return r.left>=0 && r.right<=innerWidth;});
 fs.writeFileSync('/work/screenshots/checks.json',JSON.stringify(results,null,2));
 console.log(JSON.stringify(results,null,2));
 await browser.close(); server.close();
})().catch(e=>{console.error(e);server.close();process.exitCode=1;});
