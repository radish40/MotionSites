  assert(await page.getByRole('switch').getAttribute('aria-checked') === 'true', 'Switch state');
  assert(await page.locator('.c3-tier-large').allTextContents().then(x => x.join('|')) === 'Free|$99,99/y|$199,99/y', 'Yearly prices');
  await page.getByRole('switch').press('Space');
  assert(await page.getByRole('switch').getAttribute('aria-checked') === 'false', 'Keyboard toggle');
  checks.push('Billing: monthly/yearly prices, Free unchanged, mouse and keyboard switch');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Desktop overflow');
  await page.locator('.c3-card').nth(1).hover();
  await page.waitForTimeout(700);
  assert(await page.locator('.c3-card').nth(1).evaluate(el => getComputedStyle(el).transform !== 'none'), 'Hover transform');
  await page.mouse.move(10, 10);
  await page.waitForTimeout(700);
  await page.evaluate(() => document.activeElement?.blur());
  const video = await page.evaluate(async () => {
    const v = document.querySelector('video');
    const info = { duration: v.duration, width: v.videoWidth, height: v.videoHeight, autoplay: !v.paused, loop: v.loop, muted: v.muted };
    v.pause(); v.currentTime = 2;
    await new Promise(resolve => v.addEventListener('seeked', resolve, { once: true }));
    return info;
  });
  assert(video.width > 0 && video.autoplay && !video.loop && video.muted, 'Video decoded/autoplay');
  await page.screenshot({ path: 'screenshots/desktop.png', fullPage: true });
  await page.evaluate(async () => {
    const v = document.querySelector('video');
    window.__videoEnded = 0;
    v.addEventListener('ended', () => { window.__videoEnded++; });
    v.currentTime = v.duration - .3;
    await v.play();
  });
  await page.waitForFunction(() => window.__videoEnded > 0);
  await page.waitForFunction(() => { const v = document.querySelector('video'); return v.currentTime < v.duration - .3; }, null, { timeout: 10000 });
  assert(await page.evaluate(() => { const v = document.querySelector('video'); return v.currentTime < v.duration - .3; }), 'Reverse seeking');
  await page.waitForFunction(() => { const v = document.querySelector('video'); return window.__videoEnded > 0 && !v.paused && v.currentTime < 1.5; }, null, { timeout: 45000 });
  checks.push('Video: decoded original asset, muted autoplay, no loop, natural ended event reverses and resumes forward at zero');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(400);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile overflow');
  assert(await page.locator('.c3-hamburger').isVisible(), 'Hamburger visible');
  assert(!(await page.locator('.c3-nav').isVisible()), 'Menu initially hidden');
