  page.on('response', r => { if (r.status() >= 400) failedRequests.push(`${r.status()} ${r.url()}`); });
  await page.goto(`http://localhost:4173${base}`, { waitUntil: 'networkidle' });
  await page.waitForFunction(() => document.querySelector('video').readyState >= 2);
