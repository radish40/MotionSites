const mime = {'.html':'text/html','.js':'text/javascript','.css':'text/css','.ttf':'font/ttf','.woff2':'font/woff2','.json':'application/json'};
const server = http.createServer((req,res)=>{
  let pathname = decodeURIComponent(req.url.split('?')[0]);
  if(!pathname.startsWith(base)){res.writeHead(404);return res.end('Not found')}
  const relative = pathname.slice(base.length) || 'index.html';
  const file = path.resolve('dist', relative);
  if(!file.startsWith(path.resolve('dist')+path.sep)){res.writeHead(403);return res.end()}
  try{res.setHeader('Content-Type',mime[path.extname(file)]||'application/octet-stream');res.end(fs.readFileSync(file))}catch{res.writeHead(404);res.end('Not found')}
});
