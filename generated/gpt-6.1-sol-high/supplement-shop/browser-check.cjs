const { chromium } = require('/app/node_modules/playwright-core');
const http = require('http');
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const base = '/motionsites-results/supplement-shop/';
const server = http.createServer((req,res) => {
  let name = decodeURIComponent(req.url.split('?')[0]);
  if(name===base.slice(0,-1)) {res.writeHead(302,{Location:base}); return res.end();}
  name = name.startsWith(base) ? name.slice(base.length) : name.slice(1);
  const file = path.join('/work/dist',name || 'index.html');
  try { const data = fs.readFileSync(file); const ext=path.extname(file); res.setHeader('Content-Type',({'.html':'text/html','.js':'text/javascript','.css':'text/css','.webp':'image/webp','.woff2':'font/woff2'})[ext]||'application/octet-stream'); res.end(data); } catch {res.writeHead(404);res.end('Not found');}
});
(async()=>{
 await new Promise(r=>server.listen(4173,'0.0.0.0',r));
 const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const errors=[], failures=[], checks=[];
 const page = await browser.newPage({viewport:{width:1440,height:1000}, deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('requestfailed',req=>failures.push({url:req.url(),error:req.failure()?.errorText}));
 await page.goto('http://127.0.0.1:4173'+base,{waitUntil:'networkidle'});
 await page.evaluate(()=>document.fonts.ready);
 await page.waitForTimeout(900);
 assert.equal(await page.locator('h1').textContent(),'Supplements');
 assert.equal(await page.locator('.phone').evaluate(el=>el.offsetWidth),375);
 assert.equal(await page.locator('.phone').evaluate(el=>el.offsetHeight),812);
 assert(await page.locator('.product-slot img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0)));
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 checks.push('Desktop 1440x1000: correct phone dimensions, images loaded, no page overflow');
 await page.screenshot({path:'/work/screenshots/desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Open menu',exact:true}).click();
 await page.waitForTimeout(350);
 assert(await page.getByRole('dialog',{name:'Navigation menu'}).isVisible());
 await page.getByRole('button',{name:'Products',exact:true}).click();
 await page.waitForTimeout(350);
 await page.getByRole('button',{name:'Tablets',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Tablets',exact:true}).getAttribute('aria-pressed'),'true');
 await page.getByRole('button',{name:'Capsules',exact:true}).click();
 await page.getByRole('button',{name:'Increase quantity',exact:true}).click();
 assert.equal(await page.getByTestId('quantity').textContent(),'2');
 const priceText=await page.locator('.price').textContent(); assert(['$60.00','$50.00','$70.00'].includes(priceText));
 await page.getByRole('button',{name:'Decrease quantity',exact:true}).click();
 assert.equal(await page.getByTestId('quantity').textContent(),'1');
 checks.push('Menu navigation, categories, quantity increment/decrement and total pricing passed');
 await page.getByRole('button',{name:'Buy Now',exact:true}).click();
 assert(await page.getByRole('dialog',{name:'Added to bag'}).isVisible());
 await page.getByRole('button',{name:'View bag · 11 items',exact:true}).click();
 assert(await page.getByRole('dialog',{name:'Shopping bag'}).isVisible());
 await page.getByRole('button',{name:'Close dialog',exact:true}).click();
 checks.push('Buy Now adds the selected quantity, shows confirmation, and updates bag badge');
 await page.waitForTimeout(500);
 let before=await page.locator('h2').textContent();
 await page.locator('.product-slot').nth(3).click();
 await page.waitForTimeout(550);
 assert.notEqual(await page.locator('h2').textContent(),before);
 await page.getByRole('button',{name:'Increase quantity',exact:true}).click();
 await page.waitForTimeout(3700);
 assert.equal(await page.getByTestId('quantity').textContent(),'1');
 checks.push('Adjacent product navigation and three-second autoplay passed; quantity resets');
 await page.getByRole('button',{name:'Open menu',exact:true}).click();
 await page.waitForTimeout(350);
 await page.getByRole('button',{name:'Close menu',exact:true}).click();
 await page.waitForTimeout(350);
 const names=[]; for(let i=0;i<4;i++){names.push(await page.locator('h2').textContent()); await page.locator('.product-slot').nth(3).click(); await page.waitForTimeout(500);}
 assert.equal(names[0],names[3]); checks.push('Carousel loops through all three products');
 await page.setViewportSize({width:390,height:844});
 await page.reload({waitUntil:'networkidle'}); await page.waitForTimeout(900);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 const rect=await page.locator('.phone').boundingBox(); assert(rect.x>=0&&rect.y>=0&&rect.x+rect.width<=390&&rect.y+rect.height<=844);
 await page.screenshot({path:'/work/screenshots/mobile.png',fullPage:true});
 checks.push('Mobile 390x844: full frame visible, no horizontal or vertical overflow');
 const fonts=await page.evaluate(()=>({dmSans:document.fonts.check('400 16px "DM Sans"'),inter:document.fonts.check('600 16px Inter'),status:document.fonts.status}));
 assert.equal(errors.length,0);checks.push('No browser script errors');
 fs.writeFileSync('/work/browser-checks.json',JSON.stringify({checks,errors,failures,fonts,carouselLoop:names},null,2));
 console.log(JSON.stringify({checks,errors,failures,fonts},null,2));
 await browser.close();server.close();
})().catch(e=>{console.error(e);server.close();process.exit(1);});
